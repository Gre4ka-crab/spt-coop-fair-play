using BepInEx.Configuration;
using HarmonyLib;
using PrivateStack.FairPlay;
using System;
using System.IO;
using System.Linq;

int passed=0;
void Check(bool condition,string name){if(!condition)throw new Exception(name);passed++;Console.WriteLine("PASS "+name);}
var folder=Path.GetFullPath(args[0]);Directory.CreateDirectory(folder);
var path=Path.Combine(folder,"fixture.cfg");
File.WriteAllText(path,"[Map]\nEnemies = true\nZoom = 9\nTitle = untrusted\n");
var before=File.ReadAllBytes(path);
var file=new ConfigFile(path,false){SaveOnConfigSet=false};
var enemies=file.Bind("Map","Enemies",false,new ConfigDescription("marker"));
var zoom=file.Bind("Map","Zoom",2f,new ConfigDescription("zoom",new AcceptableValueRange<float>(1,10)));
var title=file.Bind("Map","Title","approved",new ConfigDescription("caption"));
var unowned=file.Bind("Personal","Network","mine","");
var original=enemies.Description;
var locks=new SettingsLock(new Harmony("private.fairplay.fixture"));
locks.Add(enemies,"false");locks.Add(zoom,null);locks.Add(title,null);
Check(!enemies.Value&&zoom.Value==2f&&title.Value=="approved","untrusted cfg does not become baseline");
Check(before.SequenceEqual(File.ReadAllBytes(path)),"activation leaves cfg bytes unchanged");
enemies.BoxedValue=true;zoom.BoxedValue=8f;title.BoxedValue="cheat";
Check(!enemies.Value&&zoom.Value==2f&&title.Value=="approved","real Harmony boxed setters block Boolean Single String");
enemies.Value=true;zoom.Value=7f;title.Value="changed";
Check(!enemies.Value&&zoom.Value==2f&&title.Value=="approved","direct typed writes are repaired");
File.WriteAllText(path,"[Map]\nEnemies = true\nZoom = 10\nTitle = disk-edit\n");file.Reload();
Check(!enemies.Value&&zoom.Value==2f&&title.Value=="approved","ConfigFile.Reload cannot unlock cfg");
unowned.Value="personal";Check(unowned.Value=="personal","unowned personal setting remains editable");
var tag=enemies.Description.Tags.Single();
Check((bool?)tag.GetType().GetField("Browsable")!.GetValue(tag)==false&&(bool?)tag.GetType().GetField("ReadOnly")!.GetValue(tag)==true,"ConfigurationManager tags hide and lock");
locks.Verify();Check(true,"installed prefix ownership verified");
locks.Dispose();enemies.BoxedValue=true;
Check(enemies.Value&&ReferenceEquals(original,enemies.Description),"unload restores descriptions and removes only own patches");
var notice=new NoticeState();
notice.Transient("denied",100,10);
Check(notice.Visible(109)&&!notice.Visible(110),"denial expires while no successful raid starts");
notice.Transient("denied again",200,10);notice.ClearTransient();
Check(!notice.Visible(201),"successful headless transition clears earlier local-host notice");
notice.Fault("policy broken");notice.Transient("ordinary denial",300,10);notice.ClearTransient();
Check(notice.Visible(long.MaxValue)&&notice.Text=="policy broken","policy failure remains visible through expiry and ready transitions");
Console.WriteLine("{\"status\":\"PASS_ACTUAL_BEPINEX_HARMONY_FIXTURE_NOT_UNITY\",\"passed\":"+passed+"}");
